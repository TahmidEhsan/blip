function symbolFor(id, spec) {
  const [name, weight = 'bold'] = spec.split(':');
  const file = join(assets, weight, weight === 'regular' ? `${name}.svg` : `${name}-${weight}.svg`);
  const svg = readFileSync(file, 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] || '0 0 256 256';
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  return `<symbol id="${id}" viewBox="${viewBox}">${inner}</symbol>`;
}

const symbols = Object.entries(ICONS).map(([id, spec]) => symbolFor(id, spec));
const sprite = `<svg xmlns="http://www.w3.org/2000/svg" fill="currentColor"><!-- Generated by scripts/build-icons.mjs from @phosphor-icons/core (MIT). Do not edit by hand. -->\n${symbols.join('\n')}\n</svg>\n`;
writeFileSync(join(root, 'public', 'assets', 'icons.svg'), sprite);
console.log(`icons.svg: ${symbols.length} symbols`);
